#!/bin/sh
# Цикл вотчера: тик раз в 5 минут по стенным часам (без дрейфа).
# STATE_FILE лежит на примонтированном волюме (/data) — переживает
# рестарты и редеплои машины. Выход watch.py игнорируем специально:
# мёртвый токен бота (exit 1) не должен останавливать наблюдение.
while true; do
  python3 /app/scripts/watch.py
  sleep $((300 - $(date +%s) % 300))
done
